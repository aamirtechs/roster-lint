'use strict';

// Mini-bundler for the browser build. The src modules in this repo are ES
// modules, so this script reads the pure core module(s), strips the Node-only
// import lines, replaces them with small stubs that throw only if a Node-only
// helper is called, removes the export keywords, and emits docs/app.js with
// the core API exposed on window. The browser app therefore runs the exact
// same code as the library and CLI. Node-only entry points stay in src/cli.js
// and are never bundled. No dependencies, no build tooling beyond Node.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, 'docs', 'app.js');
const GLOBAL_NAME = "RosterLint";
const STUB = `const __nodeOnly = () => { throw new Error('Loading files from disk is Node only. In the browser, use rosterFromCsvText and parseConfigText with in-memory content.'); };\nconst fs = { readFileSync: __nodeOnly };`;
const CORE_FILES = ['src/index.js'];

function transform(code) {
  const names = [];
  let out = code.replace(/import\s+[\s\S]*?from\s+['"](?:node:)?(?:fs|path)['"];?/g, '');
  out = out.replace(/import\s+['"](?:node:)?(?:fs|path)['"];?/g, '');
  out = out.replace(/export\s*\{([^}]*)\}/g, (m, inner) => {
    for (const part of inner.split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop().trim();
      if (name) names.push(name);
    }
    return '';
  });
  out = out.replace(/export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\s)/g, '');
  const re = /(?:^|\n)(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/g;
  return { code: out, names };
}

const chunks = [];
const exported = [];
for (const rel of CORE_FILES) {
  const raw = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const found = [];
  for (const m of raw.matchAll(/export\s+(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/g)) found.push(m[1]);
  for (const m of raw.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop().trim();
      if (name) found.push(name);
    }
  }
  const { code } = transform(raw);
  chunks.push('// Source: ' + rel + '\n' + code.trim());
  for (const n of found) if (!exported.includes(n)) exported.push(n);
}

const header = '/* roster-lint browser bundle. Generated by build-web.js from src/. Do not edit by hand. */\n' + "'use strict';\n";
const body = STUB + '\n' + chunks.join('\n\n') + '\n';
const footer = '\nwindow.' + GLOBAL_NAME + ' = { ' + exported.join(', ') + ' };\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + body + footer, 'utf8');
console.log('Wrote ' + path.relative(process.cwd(), OUT) + ' exposing window.' + GLOBAL_NAME + ' with ' + exported.length + ' exports.');
